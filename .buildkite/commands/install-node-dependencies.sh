#!/bin/bash

set -eu

PLATFORM=$(uname -s)
ARCHITECTURE=$(uname -m)
NODE_VERSION=$(node --version)
PACKAGE_HASH=$(hash_file package-lock.json)

PATCHES_HASH=nopatch
if [ -d apps/studio/patches ]; then
  PATCHES_HASH=$( hash_directory apps/studio/patches )
fi

CACHEKEY="$BUILDKITE_PIPELINE_SLUG-npm-$PLATFORM-$ARCHITECTURE-node-$NODE_VERSION-$PACKAGE_HASH-$PATCHES_HASH"

LOCAL_NPM_CACHE=./vendor/npm
mkdir -p $LOCAL_NPM_CACHE
echo "--- :npm: Set npm to use $LOCAL_NPM_CACHE for cache"
# Absolute, because npm resolves a relative cache path against the directory it runs in, while for `tools/compare-perf`—which builds 2 checkouts in different dirs—we want to share the npm cache
npm set cache "$PWD/$LOCAL_NPM_CACHE"
echo "npm cache set to $(npm get cache)"

# On Windows, `npm ci` spends about 2 minutes writing the packages into node_modules, against 20 s on Mac.
# So Windows also caches node_modules itself, keyed on everything that decides its content: the lockfile,
# the patches, the OS, the CPU and the Node version (which brings its npm).
# Writing its 100,000 files takes Windows about a minute on one core, so the cache comes in shards
# that are extracted in parallel. Bump the version in the key to drop every entry, e.g. if one turns out to be broken.
IS_WINDOWS=false
case "$PLATFORM" in
  MINGW* | MSYS* | CYGWIN*) IS_WINDOWS=true ;;
esac
NODE_MODULES_SHARDS=8
NODE_MODULES_CACHEKEY="$BUILDKITE_PIPELINE_SLUG-node-modules-v3-$PLATFORM-$ARCHITECTURE-node-$NODE_VERSION-$PACKAGE_HASH-$PATCHES_HASH"
RESTORE_NODE_MODULES=false
if [ "$IS_WINDOWS" = true ] && [ ! -e node_modules ]; then
  RESTORE_NODE_MODULES=true
fi

echo "--- :npm: Restore caches if present"
# The npm cache is needed even when node_modules comes from its cache: packaging the app runs `npm install` for its bundle.
pids=()
restore_cache "$CACHEKEY" &
pids+=($!)
if [ "$RESTORE_NODE_MODULES" = true ]; then
  for shard in $(seq 0 $((NODE_MODULES_SHARDS - 1))); do
    restore_cache "$NODE_MODULES_CACHEKEY-$shard-of-$NODE_MODULES_SHARDS" &
    pids+=($!)
  done
fi
for pid in "${pids[@]}"; do
  wait "$pid"
done

NODE_MODULES_RESTORED=false
if [ "$RESTORE_NODE_MODULES" = true ]; then
  # When a shard is missing, `npm ci` below removes the others, as it empties node_modules first.
  if node .buildkite/commands/node-modules-shards.mjs check "$NODE_MODULES_SHARDS"; then
    NODE_MODULES_RESTORED=true
  fi
fi

if [ "$NODE_MODULES_RESTORED" = true ]; then
  echo "--- :npm: Link the workspaces"
  node .buildkite/commands/workspace-links.mjs add

  echo "--- :npm: Check that package.json and package-lock.json agree"
  # `npm ci` runs this check before it installs anything, and `--dry-run` stops it there.
  # Its output lists what a real run would change, so it is hidden; a mismatch is reported on stderr.
  npm ci --dry-run --ignore-scripts --prefer-offline --no-audit --no-fund "$@" > /dev/null

  echo "--- :npm: Run postinstall"
  npm run postinstall
  exit 0
fi

echo "--- :npm: Install Node dependencies"

MAX_SOCKETS=15 # Default value from npm

# To avoid constant ECONNRESET errors a limit is set for Linux,
# as this is not happening with the Mac jobs.
# This issue is being tracked here:
# https://github.com/npm/cli/issues/4652
if [ "$PLATFORM" = "Linux" ]; then
  MAX_SOCKETS=1
fi

npm ci \
  --unsafe-perm \
  --prefer-offline \
  --no-audit \
  --no-progress \
  --maxsockets "$MAX_SOCKETS" \
  "$@"

echo "--- :npm: Save cache if necessary"
# Notice that, outside Windows, we don't cache the local node_modules.
# Those get regenerated by npm ci as per Node reccomendations.
# What we are caching is the root npm folder, which stores pacakge downloads so they are available if the package.json resolution demands them.
#
# npm stores temporary files in ~/.npm that we don't want to extract because they might run into naming conflicts.
# So, before archiving it, we remove those tmp files.
#
# Example: https://buildkite.com/automattic/gutenberg-mobile/builds/8857#018e37eb-7afc-4280-b736-cba76f02f1a3/524
rm -rf "$LOCAL_NPM_CACHE/_cacache/tmp"
save_cache "$LOCAL_NPM_CACHE" "$CACHEKEY"

# Only trunk saves node_modules. npm checks the packages of its cache against the lockfile's hashes,
# but nothing checks a restored node_modules, so a pull request must not write the copy that others use.
if [ "$IS_WINDOWS" = true ] && [ "${BUILDKITE_BRANCH:-}" = trunk ]; then
  echo "--- :npm: Save node_modules cache if necessary"
  # `save_cache` archives one folder, so move each shard's part of the node_modules folders into its own
  # (a move is a rename, so it takes no time), without the links to the workspaces.
  NODE_MODULES_STAGING=vendor/node-modules-cache
  node .buildkite/commands/workspace-links.mjs remove
  node .buildkite/commands/node-modules-shards.mjs stage "$NODE_MODULES_STAGING" "$NODE_MODULES_SHARDS"
  pids=()
  for shard in $(seq 0 $((NODE_MODULES_SHARDS - 1))); do
    # Paths relative to the shard's folder, so that `restore_cache` extracts them in place.
    save_cache "$NODE_MODULES_STAGING/$shard" "$NODE_MODULES_CACHEKEY-$shard-of-$NODE_MODULES_SHARDS" "" --use_relative_path_in_tar &
    pids+=($!)
  done
  for pid in "${pids[@]}"; do
    wait "$pid"
  done
  node .buildkite/commands/node-modules-shards.mjs unstage "$NODE_MODULES_STAGING"
  rm -rf "$NODE_MODULES_STAGING"
  node .buildkite/commands/workspace-links.mjs add
fi
