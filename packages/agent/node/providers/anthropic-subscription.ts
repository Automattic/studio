import { anthropicProvider } from './anthropic';
import type { AiProvider, ApiKeyValidation } from './types';

export const anthropicSubscriptionProvider = {
	...anthropicProvider,
	auth: {
		type: 'api-key',
		async validate( token: string ): Promise< ApiKeyValidation > {
			if ( ! /^sk-ant-oat01-[A-Za-z0-9_-]+$/.test( token ) ) {
				return {
					status: 'invalid',
					message: 'Enter a subscription token generated by claude setup-token, not an API key.',
				};
			}
			// Check authentication on the first turn, without spending inference tokens on save.
			return { status: 'unverifiable' };
		},
	},
} satisfies AiProvider;
