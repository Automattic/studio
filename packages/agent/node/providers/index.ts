import { __ } from '@wordpress/i18n';
import { FileCredentialStore, getOrCreateDeviceId } from '../credential-store';
import { anthropicProvider } from './anthropic';
import { anthropicSubscriptionProvider } from './anthropic-subscription';
import { CHATGPT_PI_PROVIDER, createChatGptProvider, signInWithChatGpt } from './chatgpt';
import { InvalidAiProviderCredentialsError } from './types';
import { wpcomProvider } from './wpcom';
import type { AiProvider, ApiKeyValidation, ProviderCredentials } from './types';
import type { AiProviderId } from '@studio/agent/protocol/providers';

export { InvalidAiProviderCredentialsError } from './types';

/** Studio's host adapter; inference providers implement only AiProvider. */
export interface StudioAiProvider extends Omit< AiProvider, 'auth' > {
	auth:
		| {
				type: 'api-key';
				validate: ( key: string ) => Promise< ApiKeyValidation >;
				getPrompt: () => string;
				getMissingKeyMessage: () => string;
		  }
		| { type: 'account'; isConnected: () => Promise< boolean > }
		| {
				type: 'oauth';
				isConnected: () => Promise< boolean >;
				login: ( options: {
					openUrl: ( url: string ) => Promise< void >;
					signal?: AbortSignal;
				} ) => Promise< void >;
				disconnect: () => Promise< void >;
		  };
	environmentKeys: readonly string[];
	autoFallbackWhenUnavailable: boolean;
	isPreferred?: () => boolean;
	connect?: ( login: () => Promise< void > ) => Promise< boolean >;
	getConnectionMessages?: (
		apiKey?: string
	) => Promise< { status?: string; success?: string; info?: string } >;
	getErrorHint?: () => string;
	resolveEnv( options: {
		apiKey?: string;
		sessionId?: string;
		userAgent: string;
	} ): Promise< Record< string, string > >;
	resolveCredentials(
		env: Record< string, string >
	):
		| { ok: true; creds: ProviderCredentials }
		| { ok: false; reason: string }
		| Promise< { ok: true; creds: ProviderCredentials } | { ok: false; reason: string } >;
}

const credentials = new FileCredentialStore();

export const AI_BACKEND_PROVIDERS: Readonly< Record< AiProviderId, StudioAiProvider > > = {
	wpcom: wpcomProvider,
	chatgpt: {
		...createChatGptProvider( credentials ),
		auth: {
			type: 'oauth',
			isConnected: async () => ( await credentials.read( CHATGPT_PI_PROVIDER ) )?.type === 'oauth',
			login: async ( options ) =>
				signInWithChatGpt( {
					...options,
					credentials,
					deviceId: await getOrCreateDeviceId(),
				} ),
			disconnect: () => credentials.delete( CHATGPT_PI_PROVIDER ),
		},
		environmentKeys: [],
		autoFallbackWhenUnavailable: false,
		resolveEnv: async () => ( {} ),
		async resolveCredentials() {
			const credential = await credentials.read( CHATGPT_PI_PROVIDER );
			return credential?.type === 'oauth'
				? { ok: true, creds: { apiKey: credential.access, baseURL: 'https://api.openai.com/v1' } }
				: { ok: false, reason: __( 'Sign in with ChatGPT first.' ) };
		},
	},
	'anthropic-api-key': {
		...anthropicProvider,
		auth: {
			type: 'api-key',
			async validate( key ) {
				// The core provider reports API outcomes; Studio owns localized messages.
				const validation = await anthropicProvider.auth.validate( key );
				return validation.status === 'invalid'
					? {
							status: 'invalid',
							message: __( 'Anthropic rejected this API key. Check the key and try again.' ),
					  }
					: validation;
			},
			getPrompt: () => __( 'Enter your Anthropic API key (will be saved for future use):' ),
			getMissingKeyMessage: () => 'Add an Anthropic API key first.',
		},
		environmentKeys: [
			'ANTHROPIC_API_KEY',
			'ANTHROPIC_AUTH_TOKEN',
			'ANTHROPIC_BASE_URL',
			'ANTHROPIC_CUSTOM_HEADERS',
		],
		autoFallbackWhenUnavailable: false,
		getErrorHint: () => __( 'Use /api-key to update the Anthropic API key.' ),
		getConnectionMessages: async ( apiKey ) =>
			apiKey ? {} : { info: __( 'No Anthropic API key saved. Use /api-key to enter one.' ) },
		async resolveEnv( { apiKey } ) {
			if ( ! apiKey ) {
				throw new InvalidAiProviderCredentialsError(
					__(
						'Anthropic API key required. Switch to Anthropic · API key with /provider to save one.'
					)
				);
			}
			return { ANTHROPIC_API_KEY: apiKey };
		},
		resolveCredentials( env ) {
			const apiKey = env.ANTHROPIC_API_KEY?.trim();
			if ( ! apiKey ) {
				return {
					ok: false,
					reason:
						'Anthropic provider selected but ANTHROPIC_API_KEY is not set. Switch to the Anthropic · API key provider with /provider and save a key.',
				};
			}
			return { ok: true, creds: { apiKey, baseURL: 'https://api.anthropic.com' } };
		},
	},
	'anthropic-subscription': {
		...anthropicSubscriptionProvider,
		auth: {
			type: 'api-key',
			async validate( token ) {
				const result = await anthropicSubscriptionProvider.auth.validate( token );
				return result.status === 'invalid'
					? {
							status: 'invalid',
							message: __(
								'Enter a subscription token generated by claude setup-token, not an API key.'
							),
					  }
					: result;
			},
			getPrompt: () => __( 'Run claude setup-token, then paste the subscription token:' ),
			getMissingKeyMessage: () => __( 'Add a Claude subscription token first.' ),
		},
		environmentKeys: [ 'CLAUDE_CODE_OAUTH_TOKEN', 'ANTHROPIC_OAUTH_TOKEN' ],
		autoFallbackWhenUnavailable: false,
		getErrorHint: () => __( 'Run claude setup-token and use /api-key to replace the token.' ),
		async resolveEnv( { apiKey } ) {
			if ( ! apiKey ) {
				throw new InvalidAiProviderCredentialsError(
					__( 'Add a Claude subscription token first.' )
				);
			}
			return { CLAUDE_CODE_OAUTH_TOKEN: apiKey };
		},
		resolveCredentials( env ) {
			const token = env.CLAUDE_CODE_OAUTH_TOKEN?.trim();
			return token
				? { ok: true, creds: { apiKey: token, baseURL: 'https://api.anthropic.com' } }
				: { ok: false, reason: __( 'Add a Claude subscription token first.' ) };
		},
	},
};
